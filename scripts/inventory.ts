/**
 * Parking inventory CLI. See docs/DATA_PIPELINE.md.
 *
 *   npm run inventory -- import <facts.csv|facts.json> [more files…] [--dry-run]
 *   npm run inventory -- validate
 *   npm run inventory -- report
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { mergeRows, rowsFromFile } from "@/lib/inventory/import";
import { venueInventorySchema, type VenueInventory } from "@/lib/inventory/schema";
import { validateCatalog, validateInventory } from "@/lib/inventory/validate";
import { inventoryFacilities, inventoryVenue } from "@/lib/inventory/to-domain";
import { VENUES as SEED_VENUES } from "@/lib/data/venues";
import { isIndexableVenue, substantiveFacilities } from "@/lib/seo";

const DIR = resolve(import.meta.dirname, "../src/data/inventory");
const STALE_PRICE_DAYS = 180;

function load(): Record<string, VenueInventory> {
  const out: Record<string, VenueInventory> = {};
  for (const file of readdirSync(DIR).filter((f) => f.endsWith(".json")).sort()) {
    out[file.replace(/\.json$/, "")] = venueInventorySchema.parse(JSON.parse(readFileSync(join(DIR, file), "utf8")));
  }
  return out;
}

/** Stable, reviewable JSON: sorted keys at every level. */
function stable(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(stable);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value)
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([k, v]) => [k, stable(v)]),
    );
  }
  return value;
}

function writeIndex(slugs: string[]) {
  const ident = (s: string) => s.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase()).replace(/^(\d)/, "_$1");
  const lines = [
    "// Generated by `npm run inventory`. Do not edit by hand.",
    'import type { VenueInventory } from "@/lib/inventory/schema";',
    ...slugs.map((s) => `import ${ident(s)} from "./${s}.json";`),
    "",
    `export const INVENTORY: VenueInventory[] = [${slugs.map(ident).join(", ")}] as VenueInventory[];`,
    "",
  ];
  writeFileSync(join(DIR, "index.ts"), lines.join("\n"));
}

function validateAll(all: Record<string, VenueInventory>): string[] {
  const seed = new Map(SEED_VENUES.map((v) => [v.slug, v]));
  return [
    ...Object.entries(all).flatMap(([file, inv]) => (file !== inv.slug ? [`${file}.json declares slug ${inv.slug}`] : [])),
    ...Object.values(all).flatMap((inv) => validateInventory(inv, seed.get(inv.slug))),
    ...validateCatalog(Object.values(all), SEED_VENUES),
  ];
}

const [command, ...args] = process.argv.slice(2);

if (command === "import") {
  const dryRun = args.includes("--dry-run");
  const files = args.filter((a) => !a.startsWith("--"));
  if (!files.length) throw new Error("import needs at least one file");
  const rows = files.flatMap((f) => rowsFromFile(f, readFileSync(f, "utf8")));
  const existing = load();
  const results = mergeRows(existing, rows);
  const next = { ...existing, ...Object.fromEntries(Object.entries(results).map(([slug, r]) => [slug, r.inventory])) };
  const errors = validateAll(next);
  for (const [slug, r] of Object.entries(results)) {
    console.log(`\n${slug}: ${r.changes.length} change(s)`);
    for (const c of r.changes) console.log(`  ${c}`);
    for (const w of r.warnings) console.log(`  ! ${w}`);
  }
  if (errors.length) {
    console.error(`\n✖ Not written — ${errors.length} validation error(s):`);
    for (const e of errors) console.error(`  - ${e}`);
    process.exit(1);
  }
  if (dryRun) console.log("\n(dry run: nothing written)");
  else {
    for (const [slug, r] of Object.entries(results)) writeFileSync(join(DIR, `${slug}.json`), JSON.stringify(stable(r.inventory), null, 2) + "\n");
    writeIndex(Object.keys(next).sort());
    console.log(`\n✔ Wrote ${Object.keys(results).length} venue file(s). Review the diff, then run npm test.`);
  }
} else if (command === "validate") {
  const errors = validateAll(load());
  for (const e of errors) console.error(`- ${e}`);
  if (errors.length) process.exit(1);
  console.log("✔ inventory valid");
} else if (command === "report") {
  const seed = new Map(SEED_VENUES.map((v) => [v.slug, v]));
  const now = Date.now();
  for (const inv of Object.values(load())) {
    const venue = inventoryVenue(inv, seed.get(inv.slug));
    const lots = inventoryFacilities(inv);
    const byConfidence = lots.reduce<Record<string, number>>((m, f) => ((m[f.attribution.confidence] = (m[f.attribution.confidence] ?? 0) + 1), m), {});
    const stale = lots.flatMap((f) =>
      f.prices.filter((p) => (now - Date.parse(p.observedAt)) / 86_400_000 > STALE_PRICE_DAYS).map((p) => `${f.slug} ($${p.min}–$${p.max}, ${p.observedAt})`),
    );
    console.log(
      `${inv.slug}: ${lots.length} lots ${JSON.stringify(byConfidence)}, ${substantiveFacilities(lots).length} substantive, ` +
        `${isIndexableVenue(venue, lots) ? "INDEXABLE" : "noindex"}${stale.length ? `\n  stale prices: ${stale.join("; ")}` : ""}`,
    );
  }
} else {
  console.error("Usage: npm run inventory -- import <file…> [--dry-run] | validate | report");
  process.exit(2);
}
